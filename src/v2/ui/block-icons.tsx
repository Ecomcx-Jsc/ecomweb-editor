/** Icon bộ cột theo tỉ lệ ("33-66" → hai cột 1/3, 2/3). */
const colsCache = new Map<string, ComponentType<{ className?: string }>>();
export function columnsIcon(name: string): ComponentType<{ className?: string }> | undefined {
  const rep = /^(\d+)x(\d+)$/.exec(name); // "25x4" = 4 cột 25
  const w = rep ? Array.from({ length: Number(rep[2]) }, () => Number(rep[1])) : name.split("-").map(Number);
  if (w.length < 2 || w.some((x) => !(x > 0))) return undefined;
  if (!colsCache.has(name)) {
    const gap = 1.5, inner = 16 - gap * (w.length - 1), sum = w.reduce((a, b) => a + b, 0);
    let x = 4;
    const shapes: Shape[] = [["r", 2, 4, 20, 16, 3, 0]];
    for (const wi of w) { const cw = (inner * wi) / sum; shapes.push(["r", x, 6, cw, 12, 1.2, 1]); x += cw + gap; }
    colsCache.set(name, draw(shapes));
  }
  return colsCache.get(name);
}

